package kinuvo.ui.e2e

import kinuvo.testing.server.FakeExec
import kinuvo.testing.server.FakeHarness
import kinuvo.testing.server.FakeModelProvider
import kinuvo.testing.server.FakeModels
import kinuvo.protocol.Api
import kinuvo.protocol.ModelInfo
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

class SettingsFlowTest {
    private suspend fun AppDriver.dismissSheet() = swipe(50, 14, 50, 85)

    /** The whole SKILL.md is one field or code block, so a line of it is found inside the text. */
    private fun inFile(line: String) = "(?s).*$line.*"

    private val claude = FakeHarness("claude", "Claude Agent")

    private val models = FakeModels(
        FakeModelProvider("hosted-models", "Hosted models", needsKey = true),
        FakeModelProvider("local-models", "Local models"),
        FakeModelProvider("codex", "ChatGPT / Codex", listOf(ModelInfo("e2e-model", "Demo model", reasoning = emptyList())), signedIn = true),
    )

    @Test fun settingsJourney() = appTest("settings-journey", plugins = listOf(models, FakeExec()), harnesses = listOf(claude), scenario = { agent ->
        skill(agent, "daily", "Daily planning instructions", "Original instructions")
        connection(claude)
    }) {
        startChat()
        screenshot("chat")
        tap("Ask before acting in this Session: .*")
        await("This Session only")
        screenshot("session-only-sheet")
        dismissSheet()
        gone("This Session only")
        swipe(2, 50, 80, 50)
        await("E2E Agent")
        await("New agent")
        await("Server: .*")
        await("Search sessions")
        await("Agent settings")
        gone("Board")
        screenshot("drawer")
        swipe(70, 50, 10, 50)
        gone("Search sessions")
        tap("Agents and sessions")
        tap("Home")
        await("Today")
        await("ON THIS SERVER")
        await("Knowledge")
        gone("Search sessions")
        screenshot("drawer-home")
        tap("Today")
        await("Nothing needs you, no Session is running and no run is scheduled.")
        await("All clear")
        gone("Needs you")
        gone("Back")
        screenshot("today")
        returnToChat()
        gone("All clear")
        await(REPLY)

        tap("Message")
        type("Draft survives the sheet")
        tap(REPLY)
        tap("E2E Agent settings")
        await("Agent settings for every Session")
        await("Name")
        gone("Save")
        screenshot("agent-settings")
        scrollTo("Risk tolerance")
        tap("Risk tolerance")
        await("Anything that changes things")
        await("Never ask")
        gone("Agent settings for every Session")
        screenshot("risk-tolerance")
        tap("Back")
        await("Agent settings for every Session")
        tap("Personality and Soul")
        await("Principles, tone and rules")
        screenshot("instructions")
        tap("Back")
        await("Agent settings for every Session")
        tap("Next avatar")
        await("Save")
        screenshot("avatar-changed")
        tap("Previous avatar")
        gone("Save")

        repeat(3) { swipe(50, 40, 50, 85) }
        tapBelow("E2E Agent", "Name")
        clear()
        type("Renamed")
        await("Save")
        tap("Agent settings for every Session")
        dismissSheet()
        await("Discard changes\\?")
        screenshot("discard-dialog")
        tap("Keep editing")
        gone("Discard changes\\?")
        await("Save")
        dismissSheet()
        tap("Discard")
        gone("Agent settings for every Session")
        await("Draft survives the sheet")

        tap("E2E Agent settings")
        scrollTo("Skills")
        tap("Skills")
        tap("daily")
        tap("Edit")
        tap(inFile("Original instructions"))
        clear()
        type("Unsaved instructions")
        tap("Edit daily")
        tap("Back")
        await("Discard changes\\?")
        tap("Discard")
        tap("Edit")
        await(inFile("Original instructions"))
        gone(inFile("Unsaved instructions"))
        tap(inFile("Original instructions"))
        clear()
        type("---\nname: daily\ndescription: Daily planning instructions\n---\nSaved instructions\n")
        tap("Edit daily")
        tap("Save")
        gone("Discard changes\\?")
        await("Daily planning instructions")
        await(inFile("Saved instructions"))
        screenshot("skill-saved")
        tap("Back")
        tap("Back")
        scrollTo("Workspace")
        tap("Workspace")
        await("Shell and files")
        screenshot("workspace")
        tap("Back")
        await("Workspace")
        dismissSheet()

        tap("Agents and sessions")
        tap("Home")
        tap("Routines")
        await(".*E2E Agent, change Agent")
        await("Heartbeat.*")
        tap("New routine")
        tap("Morning brief")
        type("Unsaved routine")
        tap("New routine")
        dismissSheet()
        await("Discard changes\\?")
        tap("Keep editing")
        await("Unsaved routine")
        dismissSheet()
        tap("Discard")
        screenshot("routines")
        tap("Home and agents")
        tap("Tools & MCP")
        tap("Built-in tools")
        await("Memory")
        screenshot("tools")
        dismissSheet()
        tap("Home and agents")
        tap("Settings")
        tap("Model providers")
        await("Hosted models")
        scrollTo("Local models")
        await("No sign-in needed")
        screenshot("providers")
        scrollTo("Add OpenAI-compatible endpoint")
        tap("Add OpenAI-compatible endpoint")
        scrollTo("Endpoint Base URL")
        tap("Endpoint Base URL")
        type("http://localhost:1234/v1")
        scrollTo("Discover models")
        gone("Endpoint Model ID")
        tap("Discover models")
        scrollTo("Endpoint Model ID")
        await("Endpoint Model ID")
        screenshot("endpoint-manual-fallback")
        tap("Back")
        tap("Harnesses")
        await("Claude Agent")
        await("Link a Kinuvo Server")
        screenshot("harnesses")
        tap("Back")
        dismissSheet()

        returnToChat()
        tap("E2E Agent settings")
        await("Agent settings for every Session")
        tapBelow("E2E Agent", "Name")
        clear()
        type("Renamed")
        tap("Agent settings for every Session")
        tap("Save")
        gone("Save")
        dismissSheet()
        gone("Agent settings for every Session")
        await(REPLY)

        requests(Api.Connect, 1)
        requests(Api.CreateSession, 1)
        requests(Api.Send, 1)
        requests(Api.UpdateAgent, 1)
        assertEquals("Renamed", server.spy.params(Api.UpdateAgent).single().name)
        assertEquals("Renamed", server.harness.store.agents().single().name)
        requests(Api.SaveSkill, 1)
        assertTrue(server.spy.params(Api.SaveSkill).single().content.contains("Saved instructions"))
        requestsAtLeast(Api.ServerRules)
        requestsAtLeast(Api.Providers)
        requestsAtLeast(Api.ExecutionCatalog)
        requestsAtLeast(Api.DiscoverEndpoint)
        assertEquals("http://localhost:1234/v1", models.discovered.single().baseUrl)
    }
}
